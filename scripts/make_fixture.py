"""Regenerate the test fixtures verbatim from the Tanzil files.

  python scripts/make_fixture.py            # write tests/fixtures/*.txt
  python scripts/make_fixture.py --dry-run  # only print the diff against the current fixture

Copies the selected ayahs byte-for-byte from data/quran-simple.txt (and from
data/quran-uthmani.txt into mini_uthmani.txt). Nothing is typed by hand. The
diff against the existing fixture is printed so every change is visible.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "data"
FIXTURES = ROOT / "tests" / "fixtures"

# (surah, first ayah, last ayah) inclusive
SELECTION = [
    (1, 1, 7),
    (2, 153, 156),
    (8, 46, 46),
    (27, 30, 30),
    (55, 13, 13),
    (55, 16, 16),
    (103, 1, 3),
    (112, 1, 4),
]

HEADER = (
    "# TEST-ONLY SUBSET of the Tanzil Quran text (https://tanzil.net), generated by\n"
    "# scripts/make_fixture.py from data/. Do not edit by hand. Not a complete corpus.\n"
)


def _rows(path: Path) -> dict[tuple[int, int], str]:
    out: dict[tuple[int, int], str] = {}
    with open(path, encoding="utf-8-sig") as fh:
        for line in fh:
            line = line.rstrip("\n\r")
            if not line.strip() or line.startswith("#"):
                continue
            s, a, text = line.split("|", 2)
            out[(int(s), int(a))] = text
    return out


def build(source: dict[tuple[int, int], str]) -> list[str]:
    lines = []
    for surah, first, last in SELECTION:
        for a in range(first, last + 1):
            if (surah, a) not in source:
                raise KeyError(f"Tanzil file has no ayah {surah}:{a}")
            lines.append(f"{surah}|{a}|{source[(surah, a)]}")
    return lines


def _body(path: Path) -> list[str]:
    if not path.exists():
        return []
    return [
        ln
        for ln in path.read_text(encoding="utf-8-sig").splitlines()
        if ln.strip() and not ln.startswith("#")
    ]


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--dry-run", action="store_true", help="print the diff, write nothing")
    args = ap.parse_args(argv)

    simple_src, uthmani_src = DATA / "quran-simple.txt", DATA / "quran-uthmani.txt"
    if not simple_src.exists() or not uthmani_src.exists():
        missing = [p.name for p in (simple_src, uthmani_src) if not p.exists()]
        print(
            f"STOP: missing {', '.join(missing)} in {DATA}. Download from https://tanzil.net/download/",
            file=sys.stderr,
        )
        return 2

    new_simple = build(_rows(simple_src))
    new_uthmani = build(_rows(uthmani_src))

    old_simple = _body(FIXTURES / "mini_simple.txt")
    old_set, new_set = set(old_simple), set(new_simple)
    print(f"mini_simple.txt: {len(old_simple)} lines before, {len(new_simple)} after")
    for ln in old_simple:
        if ln not in new_set:
            print(f"  - {ln}")
    for ln in new_simple:
        if ln not in old_set:
            print(f"  + {ln}")
    if old_set == new_set:
        print("  (no differences in ayah text)")

    if args.dry_run:
        return 0

    FIXTURES.mkdir(parents=True, exist_ok=True)
    (FIXTURES / "mini_simple.txt").write_text(HEADER + "\n".join(new_simple) + "\n", encoding="utf-8")
    (FIXTURES / "mini_uthmani.txt").write_text(HEADER + "\n".join(new_uthmani) + "\n", encoding="utf-8")
    print(f"wrote {FIXTURES / 'mini_simple.txt'} and {FIXTURES / 'mini_uthmani.txt'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
